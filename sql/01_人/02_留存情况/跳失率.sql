-- ============================================
-- 功能：跳失率
-- 板块：人 › 留存情况
-- 依赖：taobao.user_behavior（小样本验证需先建沙箱表，见 10_开发沙箱_临时表.sql）
-- 状态：已完成
-- 更新：2026-09-20
-- 对应思维导图：人 › 留存情况 › 跳失率
-- ============================================
--
-- 【口径说明】
-- 标准的跳出率（Bounce Rate）是按「会话」算的：只浏览一个页面就离开的会话占比。
-- 但本数据集没有会话（session）概念，每条记录都是孤立的用户行为，
-- 无法切分会话，所以这里用近似口径：
--
--     跳失用户 = 全期只有 1 条行为记录的用户
--     跳失率   = 跳失用户数 / 总用户数
--
-- ⚠️ 分母是「去重用户数」，不是浏览量。
--    总 PV（pv_uv_puv 里的 SUM(pv)）单位是「次」，用户数单位是「人」，
--    两者相除没有意义。

USE taobao;

-- ────────────────────────────────────────────────
-- ①【小样本验证】一条语句同时算出分子和分母
-- ────────────────────────────────────────────────
-- 思路：先按 user_id 分组数出每人有多少条记录，
--       再在外层统计「只有 1 条」的人数和总人数。
SELECT COUNT(*)                                    AS 总用户数,
       SUM(IF(cnt = 1, 1, 0))                      AS 跳失用户数,
       ROUND(SUM(IF(cnt = 1, 1, 0)) / COUNT(*), 4) AS 跳失率
FROM (
    SELECT user_id, COUNT(*) AS cnt
    FROM temp_behavior
    GROUP BY user_id
) t;

-- ────────────────────────────────────────────────
-- ② 单独取跳失用户数（HAVING 的典型用法）
-- ────────────────────────────────────────────────
-- HAVING 过滤的是「分组结果」，所以它可以直接对 COUNT(*) 下条件，
-- 而 WHERE 里写 COUNT(*) 会报错（那时还没分组，聚合值不存在）。
SELECT COUNT(*) AS 跳失用户数
FROM (
    SELECT user_id
    FROM temp_behavior
    GROUP BY user_id
    HAVING COUNT(*) = 1
) t;

-- ────────────────────────────────────────────────
-- ③【全量执行】对真实表跑
-- ────────────────────────────────────────────────
SELECT COUNT(*)                                    AS 总用户数,
       SUM(IF(cnt = 1, 1, 0))                      AS 跳失用户数,
       ROUND(SUM(IF(cnt = 1, 1, 0)) / COUNT(*), 4) AS 跳失率
FROM (
    SELECT user_id, COUNT(*) AS cnt
    FROM user_behavior
    GROUP BY user_id
) t;

-- ────────────────────────────────────────────────
-- 参考：总浏览量（不是跳失率的分母，仅作对照）
-- ────────────────────────────────────────────────
SELECT SUM(pv) AS 总浏览量 FROM pv_uv_puv;
