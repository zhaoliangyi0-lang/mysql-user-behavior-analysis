-- ============================================
-- 功能：周内行为（时间序列分析）
-- 板块：人 › 行为情况 › 时间序列分析
-- 依赖：date_hour_behavior（由 日内行为.sql 产出）
-- 状态：已完成
-- 更新：2026-09-20
-- 对应思维导图：人 › 行为情况 › 时间序列分析 › 周内行为
-- ============================================
--
-- 从 date_hour_behavior（日期 × 小时）汇总到「星期几」，
-- 看一周里各天的行为分布，以及周末与工作日的差异。
-- 不回原始表 —— 那把 100 万行扫两遍，没必要。

USE taobao;

-- ────────────────────────────────────────────────
-- ① 明细：每天是星期几、当天各行为量多少
-- ────────────────────────────────────────────────
-- WEEKDAY() 是 ISO 定义：0=周一 … 5=周六、6=周日。
-- （DAYOFWEEK() 是另一套：1=周日、7=周六，两个别混用）
SELECT dates,
       ELT(WEEKDAY(dates) + 1, '周一','周二','周三','周四','周五','周六','周日') AS 星期,
       SUM(pv)   AS pv,
       SUM(cart) AS cart,
       SUM(fav)  AS fav,
       SUM(buy)  AS buy
FROM date_hour_behavior
GROUP BY dates
ORDER BY dates;

-- ────────────────────────────────────────────────
-- ② 按星期几汇总（取日均值，不是总和）
-- ────────────────────────────────────────────────
-- ⚠️ 这一步不能用 SUM。9 天数据里周六、周日各出现 2 次，
--    其余 5 天各只有 1 次 —— 直接求和会让周末天然翻倍，
--    看起来像"周末用户更活跃"，其实只是多统计了一天。
--    先按天汇总，再按星期几取平均，两个口径才可比。
SELECT ELT(wd + 1, '周一','周二','周三','周四','周五','周六','周日') AS 星期,
       ROUND(AVG(day_pv),   0) AS 日均pv,
       ROUND(AVG(day_cart), 0) AS 日均加购,
       ROUND(AVG(day_fav),  0) AS 日均收藏,
       ROUND(AVG(day_buy),  0) AS 日均购买
FROM (
    SELECT WEEKDAY(dates) AS wd,
           SUM(pv)   AS day_pv,
           SUM(cart) AS day_cart,
           SUM(fav)  AS day_fav,
           SUM(buy)  AS day_buy
    FROM date_hour_behavior
    GROUP BY dates
) t
GROUP BY wd
ORDER BY wd;

-- ────────────────────────────────────────────────
-- ③ 周末 vs 工作日
-- ────────────────────────────────────────────────
-- 同样取日均：工作日 5 天样本、周末 4 天样本，比总量没意义。
SELECT day_type AS 日型,
       ROUND(AVG(day_pv),  0) AS 日均pv,
       ROUND(AVG(day_buy), 0) AS 日均购买
FROM (
    SELECT IF(WEEKDAY(dates) >= 5, '周末', '工作日') AS day_type,
           SUM(pv)  AS day_pv,
           SUM(buy) AS day_buy
    FROM date_hour_behavior
    GROUP BY dates
) t
GROUP BY day_type;

-- ────────────────────────────────────────────────
-- ⚠️ 样本量提醒：结论只能当方向性参考
-- ────────────────────────────────────────────────
-- 清洗后的数据只覆盖 2017-11-25 ~ 2017-12-03，共 9 天：
--     11-25 周六   11-26 周日   11-27 周一   11-28 周二   11-29 周三
--     11-30 周四   12-01 周五   12-02 周六   12-03 周日
--
-- 每个星期几只有 1~2 天样本。两个额外的坑：
--   1. 12-03 是数据集的最后一天，它的「次日」不存在，
--      当天的行为量本身就可能因为数据截断而偏低。
--   2. 9 天横跨两周，如果平台在这期间做过活动或改版，
--      星期几的差异会混进"日期差异"，分不开。
--
-- 所以「周末比工作日活跃」这类结论，这个样本量撑不住。
